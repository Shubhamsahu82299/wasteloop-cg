export function isWasteRelatedCivicIssue(category: string): boolean {
  const configuredCategory = civicIssueCategories.find((item) => item.value === category);
  if (configuredCategory) return configuredCategory.requiresWasteWeight;

  const legacyCategory = category.toLowerCase();
  return legacyCategory.includes("waste") ||
    legacyCategory.includes("garbage") ||
    legacyCategory.includes("sanitation");
}

export function validateCivicCompletionWeight(
  category: string,
  wasteCollectedKg: number | undefined,
): string | null {
  if (isWasteRelatedCivicIssue(category) && wasteCollectedKg === undefined) {
    return "Record the collected waste weight before submitting this waste complaint for verification.";
  }
  if (!isWasteRelatedCivicIssue(category) && wasteCollectedKg !== undefined) {
    return "Collected waste weight only applies to waste-related complaints.";
  }
  return null;
}
